CLINICAL_CUTOFFS = {
    "inactive": {"min": 1.0, "max": 2.0, "label": "غیرفعال", "color": "#22c55e"},
    "mild": {"min": 2.0, "max": 3.0, "label": "خفیف", "color": "#f59e0b"},
    "moderate": {"min": 3.0, "max": 4.0, "label": "متوسط", "color": "#f97316"},
    "severe": {"min": 4.0, "max": 6.0, "label": "شدید / فعال بالینی", "color": "#ef4444"}
}


def get_schema_level(score: float) -> dict:
    """تعیین سطح طرحواره بر اساس نمره"""
    if score < 2.0:
        return CLINICAL_CUTOFFS["inactive"]
    elif score < 3.0:
        return CLINICAL_CUTOFFS["mild"]
    elif score < 4.0:
        return CLINICAL_CUTOFFS["moderate"]
    else:
        return CLINICAL_CUTOFFS["severe"]


